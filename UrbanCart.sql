--20 Which products are most frequently ordered together? 

SELECT
    p1."Product_name" AS product_1,
    p2."Product_name" AS product_2,
    COUNT(*) AS times_ordered_together
FROM public."FactOrderItem" f1
JOIN public."FactOrderItem" f2
    ON f1."order_id" = f2."order_id"
   AND f1."Product_id" < f2."Product_id"
JOIN public."DimProducts" p1
    ON f1."Product_id" = p1."Product_id"
JOIN public."DimProducts" p2
    ON f2."Product_id" = p2."Product_id"
GROUP BY 
    p1."Product_name",
    p2."Product_name"
ORDER BY times_ordered_together DESC
LIMIT 10;

--21. Which product pairs appear most often across all orders? 

SELECT
    p1."Product_name" AS product_1,
    p2."Product_name" AS product_2,
    COUNT(*) AS pair_frequency
FROM public."FactOrderItem" f1

JOIN public."FactOrderItem" f2
    ON f1."order_id" = f2."order_id"
   AND f1."Product_id" < f2."Product_id"

JOIN public."DimProducts" p1
    ON f1."Product_id" = p1."Product_id"

JOIN public."DimProducts" p2
    ON f2."Product_id" = p2."Product_id"

GROUP BY 
    p1."Product_name",
    p2."Product_name"

ORDER BY 
    pair_frequency DESC
LIMIT 10;



--22. Based on product co-occurrence and customer behavior, which products should 
--UrbanCart promote together to maximize cross-selling opportunities? 


SELECT
    p1."Product_name" AS product_1,
    p2."Product_name" AS product_2,
    COUNT(DISTINCT f1."order_id") AS times_ordered_together,
    ROUND(AVG(ft."Quantity" * dp."unit_price"), 2) AS avg_order_revenue
FROM public."FactOrderItem" f1
JOIN public."FactOrderItem" f2
    ON f1."order_id" = f2."order_id"
   AND f1."Product_id" < f2."Product_id"
JOIN public."FactOrderItem" ft
    ON f1."order_id" = ft."order_id"
JOIN public."DimProducts" dp
    ON ft."Product_id" = dp."Product_id"
JOIN public."DimProducts" p1
    ON f1."Product_id" = p1."Product_id"
JOIN public."DimProducts" p2
    ON f2."Product_id" = p2."Product_id"
JOIN public."Fact_orders" o
    ON f1."order_id" = o."Order_id"
   AND o."Status" = 'Completed'
GROUP BY
    p1."Product_name",
    p2."Product_name"
ORDER BY times_ordered_together DESC, avg_order_revenue DESC
LIMIT 10;

