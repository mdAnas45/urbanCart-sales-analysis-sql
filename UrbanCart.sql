--14. Which cities have the highest average order value? 


SELECT
    c."City",
    ROUND(
        SUM(ft."Quantity" * dp."unit_price") 
        / COUNT(DISTINCT o."Order_id")::numeric,
    2) AS "average_order_value"
FROM public."DimCustomers" AS c
JOIN public."Fact_orders" AS o
    ON c."customer_id" = o."Customer_id"
   AND o."Status" = 'Completed'
JOIN public."FactOrderItem" AS ft
    ON ft."order_id" = o."Order_id"
JOIN public."DimProducts" AS dp
    ON ft."Product_id" = dp."Product_id"
GROUP BY c."City"
ORDER BY "average_order_value" DESC;


--15. How does customer purchasing behavior change over time since account creation? 
SELECT
    c."customer_id",
    (EXTRACT(YEAR FROM AGE(
        o."Order_date"::timestamp, 
        c."Created_at"::timestamp
    )) * 12 
     + EXTRACT(MONTH FROM AGE(
        o."Order_date"::timestamp, 
        c."Created_at"::timestamp
    ))) AS months_since_creation,
    COUNT(DISTINCT o."Order_id") AS total_orders,
    SUM(ft."Quantity") AS total_quantity,
    ROUND(SUM(ft."Quantity" * dp."unit_price"), 2) AS total_revenue,
    ROUND(SUM(ft."Quantity" * dp."unit_price") / COUNT(DISTINCT o."Order_id"), 2) AS avg_order_value
FROM public."DimCustomers" AS c
JOIN public."Fact_orders" AS o
    ON c."customer_id" = o."Customer_id"
   AND o."Status" = 'Completed'
JOIN public."FactOrderItem" AS ft
    ON o."Order_id" = ft."order_id"
JOIN public."DimProducts" AS dp
    ON ft."Product_id" = dp."Product_id"
GROUP BY c."customer_id", months_since_creation
ORDER BY c."customer_id", months_since_creation;


