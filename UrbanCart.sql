--9. What is the average order value (AOV) and Average Basket Size? 
                              
SELECT 
    ROUND(
        SUM(p."unit_price" * f."Quantity") 
        / COUNT(DISTINCT d."Order_id")::numeric, 2
    ) AS "Average Order Value",

    ROUND(
        SUM(f."Quantity") 
        / COUNT(DISTINCT d."Order_id")::numeric, 2
    ) AS "Average Basket Size"

FROM public."FactOrderItem" AS f

LEFT JOIN public."DimProducts" AS p
    ON f."Product_id" = p."Product_id"

LEFT JOIN public."Fact_orders" AS d
    ON d."Order_id" = f."order_id"
   AND d."Status" = 'Completed';


--10. Which products are at risk of stock-out due to high sales volume and low inventory?


    SELECT 
    p."Product_id",
    p."Product_name",
    p."Stock",
    s."Total_Sales"
FROM public."DimProducts" AS p

LEFT JOIN (
    SELECT 
        f."Product_id",
        SUM(f."Quantity") AS "Total_Sales"
    FROM public."FactOrderItem" AS f
    LEFT JOIN public."Fact_orders" AS d
        ON f."order_id" = d."Order_id"
    WHERE d."Status" = 'Completed'
    GROUP BY f."Product_id"
) AS s
ON p."Product_id" = s."Product_id"

WHERE p."Stock" < 100    -- Stock threshold (adjustable)
  AND s."Total_Sales" > 10      -- Sales threshold (adjustable)
ORDER BY s."Total_Sales" DESC;



--11. Which customers contribute the highest total revenue? 

SELECT 
    c."customer_id",
    c."full_name",
    SUM(f."Quantity" * p."unit_price") AS "Total_Revenue"
FROM public."FactOrderItem" AS f

LEFT JOIN public."Fact_orders" AS o
    ON f."order_id" = o."Order_id"
   AND o."Status" = 'Completed'

