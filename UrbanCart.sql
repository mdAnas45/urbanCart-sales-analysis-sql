-- 1. How many total orders has UrbanCart received so far?

select 
	count(distinct fo."Order_id") as "Total order"
	from public."Fact_orders" fo;

--2. How many unique customers have placed at least one order? 

select fo."Customer_id"
from public."Fact_orders" fo
group by fo."Customer_id"
having count(distinct fo."Order_id") >= 1;

--3. Which cities generate the highest number of orders?

select c."City",
       count(distinct o."Order_id") as total_orders
from public."DimCustomers" c
left join public."Fact_orders" o
  on o."Customer_id" = c."customer_id"
group by c."City"
order by total_orders desc
limit 1;

--4. What percentage of customers have placed more than one order? 
with customer_orders as (
    select 
        "Customer_id",
        count(distinct "Order_id") as total_orders
    from public."Fact_orders"
    group by "Customer_id"
),
summary as (
    select
        count(*) as total_customers,
        sum(case when total_orders > 1 then 1 else 0 end) as repeat_customers
    from customer_orders
)
select 
    (repeat_customers / total_customers) *100
        as repeat_customer_percentage
from summary;


